// Generates src/theme/palette.generated.css from Tailwind's own default palette (#504).
// Tailwind's colour variables (--color-gray-50, ...) are remapped to --qm-* variables; the :root block holds the
// Dark theme (default) and :root[data-theme="light"] holds the original Tailwind values.
// Usage: node scripts/generate-theme-palette.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const themeCss = readFileSync(resolve(here, "../node_modules/tailwindcss/theme.css"), "utf8");

const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const INVERT = { 50: 950, 100: 900, 200: 800, 300: 700, 700: 300, 800: 200, 900: 100, 950: 50 };
// Families whose light tints / dark inks are inverted in the Dark theme. Shades 400-600 stay put.
const INVERTED_FAMILIES = ["slate", "gray", "zinc", "neutral", "stone", "red", "orange", "amber", "yellow", "lime",
  "green", "emerald", "teal", "cyan", "blue", "violet", "purple", "fuchsia", "pink", "rose", "sky"];
// Indigo becomes sky in Dark. 700-900 stay dark (hover / deep backgrounds); 600 is nudged so white text stays AA.
// Neutral text in 500 / 600 is too dim on dark surfaces (about 3:1), so it moves one and two steps lighter in Dark.
const NEUTRALS = ["slate", "gray", "zinc", "neutral", "stone"];
const NEUTRAL_DARK_SHIFT = { 500: 400, 600: 300 };
const INDIGO_DARK = { 50: "sky-950", 100: "sky-900", 200: "sky-800", 300: "sky-700", 400: "sky-400", 500: "sky-500",
  600: "oklch(55% 0.15 242)", 700: "sky-700", 800: "sky-800", 900: "sky-900", 950: "sky-950" };

function raw(family, shade) {
  const match = themeCss.match(new RegExp(`--color-${family}-${shade}:\\s*([^;]+);`));
  if (!match) throw new Error(`Missing --color-${family}-${shade}`);
  return match[1].trim();
}
function resolveRef(ref) {
  if (ref.startsWith("oklch")) return ref;
  const [family, shade] = ref.split("-");
  return raw(family, shade);
}

const families = [...INVERTED_FAMILIES, "indigo"];
const dark = [];
const light = [];
const mapped = [];
for (const family of families) {
  for (const shade of SHADES) {
    const name = `--qm-${family}-${shade}`;
    light.push(`  ${name}: ${raw(family, shade)};`);
    let darkValue;
    if (family === "indigo") darkValue = resolveRef(INDIGO_DARK[shade]);
    else if (NEUTRALS.includes(family)) darkValue = raw(family, NEUTRAL_DARK_SHIFT[shade] ?? INVERT[shade] ?? shade);
    else darkValue = raw(family, INVERT[shade] ?? shade);
    dark.push(`  ${name}: ${darkValue};`);
    mapped.push(`  --color-${family}-${shade}: var(${name});`);
  }
}

// Semantic tokens: surface replaces bg-white; panel* replace dark-literal slate backgrounds; on-panel* replace the
// light text and translucent overlays that sit on them.
const semantic = {
  dark: {
    surface: raw("gray", 900), panel: raw("slate", 900), "panel-raised": raw("slate", 800), "panel-deep": raw("slate", 950),
    "on-panel": "#ffffff", "on-panel-muted": raw("slate", 300), "indigo-ink": raw("sky", 300), "sky-ink": raw("sky", 300),
    "shell-a": "#1e3a8a", "shell-b": "#0f172a", "shell-c": "#020617",
    "stage-a": raw("gray", 900), "stage-b": raw("gray", 950),
  },
  light: {
    surface: "#ffffff", panel: raw("slate", 100), "panel-raised": raw("slate", 200), "panel-deep": raw("slate", 50),
    "on-panel": raw("slate", 900), "on-panel-muted": raw("slate", 600), "indigo-ink": raw("indigo", 600), "sky-ink": raw("sky", 700),
    "shell-a": raw("sky", 100), "shell-b": raw("slate", 100), "shell-c": raw("slate", 50),
    "stage-a": "#ffffff", "stage-b": raw("slate", 50),
  },
};
// "-ink" colours: light-on-dark accent text (text-amber-200 and friends) is dark ink in Light, shade 300 in Dark.
const INK_FAMILIES = ["amber", "rose", "emerald", "red", "green", "yellow", "orange", "purple", "blue", "violet", "teal", "cyan", "pink"];
for (const family of INK_FAMILIES) {
  semantic.dark[family + "-ink"] = raw(family, 300);
  semantic.light[family + "-ink"] = raw(family, 700);
}
const semanticVars = (set) => Object.entries(set).map(([key, value]) => `  --qm-${key}: ${value};`);
const semanticMapped = ["surface", "panel", "panel-raised", "panel-deep", "on-panel", "on-panel-muted", "indigo-ink", "sky-ink", ...INK_FAMILIES.map((family) => family + "-ink")]
  .map((key) => `  --color-${key}: var(--qm-${key});`);

const out = `/* GENERATED by scripts/generate-theme-palette.mjs - do not edit. See docs/AC.md "Visual theme" (#504). */
:root,
:root[data-theme="dark"] {
  color-scheme: dark;
${dark.join("\n")}
${semanticVars(semantic.dark).join("\n")}
}

/* Print always uses the Light values so pages print on white. */
@media print {
  :root[data-theme] {
  color-scheme: light;
${light.join("\n")}
${semanticVars(semantic.light).join("\n")}
  }
}

:root[data-theme="light"] {
  color-scheme: light;
${light.join("\n")}
${semanticVars(semantic.light).join("\n")}
}

@theme {
${mapped.join("\n")}
${semanticMapped.join("\n")}
}
`;
writeFileSync(resolve(here, "../src/theme/palette.generated.css"), out);
console.log(`Wrote palette.generated.css (${out.length} bytes)`);
