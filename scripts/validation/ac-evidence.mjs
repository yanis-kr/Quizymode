#!/usr/bin/env node
// Acceptance Evidence generator (AC 7.10.6, 7.10.7). Turns Playwright JSON reports into one Markdown comment per issue.
// Results are copied from the report, never judged: expected = PASSED, unexpected or flaky = FAILED, skipped = BLOCKED.
//
//   node scripts/validation/ac-evidence.mjs --issues 645,646 --report playwright-report/results.json \
//        [--report <another.json>] [--run-url <CI run URL>] [--env <where the tests ran>] [--out <dir>] [--post]
//
// Writes <out>/issue-<n>.md (default out: .artifacts/evidence) and prints a JSON summary. --post also adds the comment
// to each issue with `gh issue comment`. It never closes an issue.
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { METHODS, TEST_DIR_BY_METHOD, acIdsInTitle, parseAcMarkdown, parseArgs, parseIssueList } from "./ac-lib.mjs";

const STATUS = { expected: "PASSED", unexpected: "FAILED", flaky: "FAILED", skipped: "BLOCKED" };

/** Flattens a Playwright JSON report into [{ title, file, project, result, note }]. */
export function flattenReport(report) {
  const out = [];
  const walk = (suite) => {
    for (const spec of suite.specs ?? []) {
      for (const test of spec.tests ?? []) {
        const skipNote = (test.annotations ?? []).find((a) => a.type === "skip")?.description;
        out.push({
          title: spec.title,
          file: spec.file ?? suite.file ?? "",
          project: test.projectName ?? "",
          result: STATUS[test.status] ?? "FAILED",
          note: skipNote ?? "",
        });
      }
    }
    for (const child of suite.suites ?? []) walk(child);
  };
  for (const suite of report.suites ?? []) walk(suite);
  return out;
}

/** Worst result wins, so one failing test for an AC cannot hide behind a passing one. */
function combine(results) {
  for (const status of ["FAILED", "BLOCKED", "PASSED"]) if (results.includes(status)) return status;
  return "NOT RUN";
}

/** One row per AC of the issue: { id, method, result, detail }. */
export function evidenceRows(acs, tests, runUrl) {
  return acs.map((ac) => {
    if (!ac.method || !METHODS.includes(ac.method)) {
      return { id: ac.id, method: ac.method ?? "(none)", result: "NOT RUN", detail: "No valid [verify: <method>] tag." };
    }
    if (TEST_DIR_BY_METHOD[ac.method]) {
      const mine = tests.filter((test) => acIdsInTitle(test.title).includes(ac.id));
      if (mine.length === 0) {
        return { id: ac.id, method: ac.method, result: "NOT RUN", detail: "No test in the report names this AC." };
      }
      const detail = mine
        .map((test) => `${test.result}: ${test.title} [${test.project}]${test.note ? ` (${test.note})` : ""}`)
        .join("<br>");
      return { id: ac.id, method: ac.method, result: combine(mine.map((test) => test.result)), detail };
    }
    if (ac.method === "unit") {
      return runUrl
        ? { id: ac.id, method: "unit", result: "SEE CI", detail: `Covered by the tests of the CI run: ${runUrl}` }
        : { id: ac.id, method: "unit", result: "NOT RUN", detail: "Pass --run-url with the green CI run." };
    }
    return { id: ac.id, method: ac.method, result: "NOT RUN", detail: `Needs ${ac.method} evidence added by the agent.` };
  });
}

export function isComplete(rows) {
  return rows.length > 0 && rows.every((row) => row.result === "PASSED" || row.result === "SEE CI");
}

export function renderComment(issue, rows, meta) {
  // Backslashes first, so an input that already holds "\|" cannot end up as an unescaped pipe.
  const cell = (text) => String(text).replace(/\\/g, "\\\\").replace(/\|/g, "\\|");
  const lines = [
    "## Acceptance Evidence",
    "",
    `Generated by \`scripts/validation/ac-evidence.mjs\` from Playwright reports. Issue #${issue}.`,
    "",
    `- Environment: ${meta.env || "not stated"}`,
    `- CI run: ${meta.runUrl || "not stated"}`,
    `- Commit: ${meta.commit || "not stated"}`,
    "",
    "| AC | Method | Result | Evidence |",
    "| --- | --- | --- | --- |",
    ...rows.map((row) => `| AC ${row.id} | ${row.method} | ${row.result} | ${cell(row.detail)} |`),
    "",
    isComplete(rows)
      ? "Every AC of this issue has evidence by its tagged method."
      : "Not every AC has evidence yet. FAILED, BLOCKED and NOT RUN rows keep this issue open.",
  ];
  return `${lines.join("\n")}\n`;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const issues = parseIssueList(args.issues);
  const reports = [].concat(args.report ?? []).filter((value) => typeof value === "string");
  if (issues.length === 0 || reports.length === 0) {
    console.error("Usage: ac-evidence.mjs --issues <n,n> --report <results.json> [--report ...] [--run-url <url>] [--env <text>] [--out <dir>] [--post]");
    process.exit(2);
  }
  const root = process.cwd();
  const acs = parseAcMarkdown(fs.readFileSync(path.join(root, "docs/AC.md"), "utf8"));
  const tests = reports.flatMap((file) => flattenReport(JSON.parse(fs.readFileSync(file, "utf8"))));
  const runUrl = typeof args["run-url"] === "string" ? args["run-url"] : "";
  let commit = "";
  try {
    commit = execFileSync("git", ["rev-parse", "HEAD"], { cwd: root, encoding: "utf8" }).trim();
  } catch {
    // Not a git checkout; the comment says "not stated".
  }
  const outDir = path.resolve(typeof args.out === "string" ? args.out : ".artifacts/evidence");
  fs.mkdirSync(outDir, { recursive: true });

  const summary = issues.map((issue) => {
    const rows = evidenceRows(acs.filter((ac) => ac.issues.includes(issue)), tests, runUrl);
    const file = path.join(outDir, `issue-${issue}.md`);
    fs.writeFileSync(file, renderComment(issue, rows, { env: typeof args.env === "string" ? args.env : "", runUrl, commit }));
    if (args.post) execFileSync("gh", ["issue", "comment", String(issue), "--body-file", file], { cwd: root, stdio: "inherit" });
    return { issue, complete: isComplete(rows), acs: rows.length, open: rows.filter((r) => r.result !== "PASSED" && r.result !== "SEE CI").map((r) => `AC ${r.id}: ${r.result}`), file };
  });
  console.log(JSON.stringify(summary, null, 2));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
